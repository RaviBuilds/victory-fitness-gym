"use client";

import { useId, useState } from "react";
import { Button, ActionButton } from "@/components/ui/Button";
import { TrainingIcon } from "@/components/ui/TrainingIcon";
import {
  START_QUESTIONS,
  buildWhatsAppSummaryMessage,
  formatProfile,
  getRecommendation,
  getWeeklyPlan,
  getWhyItems,
  type GymContext,
  type PlanDayKind,
  type StartAnswers,
} from "@/components/sections/startCheckLogic";
import { appendWhatsAppMessage, buildWhatsAppHref } from "@/lib/whatsapp";
import type { TrainingIconName, WhatsAppConfig } from "@/lib/types";

/**
 * /start — RESULT STATE: one cohesive, personalised recommendation.
 *
 *   A. Starting point   — title + why it was chosen (from the answers)
 *   B. Your week        — one card per training day (DAY 01 / title / focus /
 *                         training), generated by getWeeklyPlan()
 *   C. Why this fits    — compact accordion, every item collapsed by default
 *   D. Starting profile — the visitor's answers, revealed by "View your answers"
 *   E. CTA bar          — WhatsApp (primary), membership, call, start again
 *
 * Everything is in NORMAL DOCUMENT FLOW. Expanding an accordion item or the
 * profile makes the page taller; there is no fixed height, no overflow
 * container and no inner scrollbar anywhere, so the page is the only scroll.
 *
 * Gym-agnostic: the gym name, WhatsApp config and GymContext (verified
 * programs, documented equipment, opening hours) all arrive as props from the
 * gym's own data. Nothing is hardcoded, and sections with no verified data
 * behind them simply do not render.
 */

const DAY_ICON: Record<PlanDayKind, TrainingIconName> = {
  lower: "strength",
  upper: "strength",
  full: "equipment",
  conditioning: "cardio",
  recovery: "floor",
};

export function StartResult({
  answers,
  whatsapp,
  gymName,
  membershipHref,
  callHref,
  gymContext,
  onRestart,
}: {
  answers: StartAnswers;
  whatsapp: WhatsAppConfig;
  gymName: string;
  membershipHref: string;
  callHref?: string;
  gymContext: GymContext;
  onRestart: () => void;
}) {
  const uid = useId();

  const recommendation = getRecommendation(answers);
  const plan = getWeeklyPlan(answers, gymContext);
  const whyItems = getWhyItems(answers, plan, gymContext);
  const profile = formatProfile(answers, START_QUESTIONS);

  // Both disclosures start collapsed so the result stays compact; expanding
  // either one simply grows the page.
  const [openItems, setOpenItems] = useState<string[]>([]);
  const [profileOpen, setProfileOpen] = useState(false);

  const toggleItem = (id: string) =>
    setOpenItems((prev) =>
      prev.includes(id) ? prev.filter((x) => x !== id) : [...prev, id]
    );

  const hasWhatsApp = Boolean(whatsapp?.number);
  const whatsappMessage = buildWhatsAppSummaryMessage(
    gymName,
    answers,
    START_QUESTIONS,
    recommendation,
    plan
  );
  const waHref = hasWhatsApp
    ? appendWhatsAppMessage(buildWhatsAppHref(whatsapp), whatsappMessage)
    : undefined;

  const profileId = `${uid}-profile`;

  return (
    <div className="start-workspace factory-stagger-in">
      {/* ----- A + B: starting point and the weekly plan ----- */}
      <section className="start-result-panel" aria-labelledby={`${uid}-title`}>
        <div className="start-result-head">
          <span className="factory-eyebrow">Your starting point</span>
          <h2 id={`${uid}-title`} className="start-result-title mt-3">
            {recommendation.title}
          </h2>
          <p className="start-result-lead mt-4">{recommendation.description}</p>
          <p className="start-result-because mt-2">{recommendation.rationale}</p>
        </div>

        <div className="start-week">
          <div className="start-week-head">
            <div>
              <span className="factory-eyebrow">Your week</span>
              <h3 className="start-result-sub mt-2">{plan.label}</h3>
            </div>
            <p className="start-week-summary">{plan.summary}</p>
          </div>

          <ol className="start-week-grid" role="list" data-count={plan.days.length}>
            {plan.days.map((day, i) => (
              <li
                key={day.id}
                className="start-day factory-stagger-in"
                data-kind={day.kind}
                style={{ animationDelay: `${80 + i * 50}ms` }}
              >
                <div className="start-day-top">
                  <span className="start-day-num">{day.dayLabel}</span>
                  <TrainingIcon name={DAY_ICON[day.kind]} className="start-day-icon" />
                </div>
                <h4 className="start-day-title">{day.title}</h4>
                <dl className="start-day-detail">
                  <div>
                    <dt>Focus</dt>
                    <dd>{day.focus.join(" \u00B7 ")}</dd>
                  </div>
                  <div>
                    <dt>Training</dt>
                    <dd>{day.training}</dd>
                  </div>
                </dl>
              </li>
            ))}
          </ol>

          {plan.note && <p className="start-week-note">{plan.note}</p>}
        </div>
      </section>

      {/* ----- C + D: why this fits, and the starting profile ----- */}
      <div className="start-support-row">
        {whyItems.length > 0 && (
          <section className="start-panel" aria-labelledby={`${uid}-why`}>
            <span className="factory-eyebrow">Why this fits</span>
            <h2 id={`${uid}-why`} className="start-panel-title mt-2">
              Why {gymName} fits your start
            </h2>

            <div className="start-acc mt-4">
              {whyItems.map((item, i) => {
                const open = openItems.includes(item.id);
                const triggerId = `${uid}-acc-${item.id}`;
                const panelId = `${uid}-acc-panel-${item.id}`;
                return (
                  <div key={item.id} className="start-acc-item" data-open={open}>
                    <h3>
                      <button
                        type="button"
                        id={triggerId}
                        aria-expanded={open}
                        aria-controls={panelId}
                        onClick={() => toggleItem(item.id)}
                        className="factory-focus start-acc-trigger"
                      >
                        <span className="start-acc-index" aria-hidden="true">
                          {String(i + 1).padStart(2, "0")}
                        </span>
                        <span className="start-acc-title">{item.title}</span>
                        <span className="start-acc-icon" aria-hidden="true">
                          +
                        </span>
                      </button>
                    </h3>
                    <div
                      id={panelId}
                      role="region"
                      aria-labelledby={triggerId}
                      className="start-acc-panel"
                    >
                      <div className="start-acc-clip">
                        <div className="start-acc-body">
                          {item.body.map((paragraph) => (
                            <p key={paragraph}>{paragraph}</p>
                          ))}
                        </div>
                      </div>
                    </div>
                  </div>
                );
              })}
            </div>
          </section>
        )}

        {profile.length > 0 && (
          <section
            className="start-panel"
            aria-labelledby={`${uid}-profile-title`}
            data-open={profileOpen}
          >
            <span className="factory-eyebrow">Your answers</span>
            <h2 id={`${uid}-profile-title`} className="start-panel-title mt-2">
              Your starting profile
            </h2>

            <button
              type="button"
              className="factory-focus start-profile-toggle mt-4"
              aria-expanded={profileOpen}
              aria-controls={profileId}
              onClick={() => setProfileOpen((v) => !v)}
            >
              <span>{profileOpen ? "Hide your answers" : "View your answers"}</span>
              <span className="start-profile-toggle-icon" aria-hidden="true">
                {"\u2193"}
              </span>
            </button>

            <div id={profileId} className="start-profile-panel">
              <div className="start-profile-clip">
                <dl className="start-profile-grid">
                  {profile.map((row) => (
                    <div key={row.id} className="start-profile-cell" data-id={row.id}>
                      <dt>{row.label}</dt>
                      <dd>{row.value}</dd>
                    </div>
                  ))}
                </dl>
              </div>
            </div>
          </section>
        )}
      </div>

      <p className="start-scope-note">
        This is general educational fitness guidance, not a medical assessment or
        a guaranteed outcome. The gym will adapt your starting structure to you in
        person.
      </p>

      {/* ----- E: CTA bar — the single conversion zone, in normal flow ----- */}
      <div className="start-cta-bar">
        <div className="start-cta-primary">
          {waHref ? (
            <Button href={waHref} variant="primary" className="w-full sm:w-auto">
              Send My Starting Point on WhatsApp
              <span aria-hidden="true">→</span>
            </Button>
          ) : callHref ? (
            <Button href={callHref} variant="primary" className="w-full sm:w-auto">
              Call the Gym
              <span aria-hidden="true">→</span>
            </Button>
          ) : null}
          <Button
            href={membershipHref}
            variant="secondary"
            className="w-full sm:w-auto"
          >
            View Membership Options
            <span aria-hidden="true">→</span>
          </Button>
        </div>

        <div className="start-cta-secondary">
          {/* If WhatsApp is the primary, Call remains available here too. */}
          {waHref && callHref && (
            <Button href={callHref} variant="ghost">
              Call the Gym
              <span aria-hidden="true">→</span>
            </Button>
          )}
          <ActionButton variant="ghost" onClick={onRestart}>
            <span aria-hidden="true">↺</span> Start again
          </ActionButton>
        </div>
      </div>
    </div>
  );
}
